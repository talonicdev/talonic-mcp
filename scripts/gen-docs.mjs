#!/usr/bin/env node
// Generated docs artefacts, read from real sources so nobody types them:
//
//   1. src/content/generated/tool-registry.ts — a snapshot of `tools/list` for
//      every tool the public reference documents (the public groups plus the
//      Process Plane tools; app-gated and internal groups are never in it).
//      src/content/sections/tool-reference.ts turns it into one rendered page
//      per tool on talonic.com/docs/mcp.
//   2. docs/sections.json — the dormant mirror the platform syncs into
//      @talonic/docs, rendered from src/content so it can never drift from
//      the live pages again (the publish workflow's docs-drift guard watches it).
//
//   npm run docs:gen      rebuilds, rewrites both files, rebuilds again
//
// tests/content/generated-docs.test.ts runs the same functions against src/
// and fails when either file is stale.

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { GROUPS, inventory } from "./tool-inventory.mjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
export const REGISTRY_FILE = "src/content/generated/tool-registry.ts"
export const MIRROR_FILE = "docs/sections.json"

/** Groups the public tool reference documents, in reference order. */
export const REFERENCE_GROUPS = ["core", "agent_tasks", "decision_tasks", "processes"]

/** Tools OpenAI / ChatGPT clients are not given (includeGenericExecutor: false). */
async function openAiHidden(createServer, sdk) {
  const all = await names(createServer, sdk, {})
  const openai = new Set(await names(createServer, sdk, { includeGenericExecutor: false }))
  return new Set(all.filter((n) => !openai.has(n)))
}

async function listFull(createServer, sdk, opts) {
  const server = createServer({
    apiKey: "tlnc_docs",
    baseUrl: "https://api.example.test",
    ...opts,
  })
  const [clientT, serverT] = sdk.InMemoryTransport.createLinkedPair()
  const client = new sdk.Client({ name: "gen-docs", version: "0" })
  await server.connect(serverT)
  await client.connect(clientT)
  const tools = []
  let cursor
  do {
    const page = await client.listTools(cursor ? { cursor } : {})
    tools.push(...page.tools)
    cursor = page.nextCursor
  } while (cursor)
  await client.close()
  await server.close()
  return tools
}

async function names(createServer, sdk, opts) {
  return (await listFull(createServer, sdk, opts)).map((t) => t.name)
}

function typeOf(p) {
  if (!p || typeof p !== "object") return "any"
  if (p.enum) return p.enum.map((v) => JSON.stringify(v)).join(" | ")
  if (p.const !== undefined) return JSON.stringify(p.const)
  if (Array.isArray(p.type)) return p.type.filter((t) => t !== "null").join(" | ")
  if (p.type === "array") return `${typeOf(p.items)}[]`
  if (p.type) return p.type
  const alts = p.anyOf ?? p.oneOf
  if (alts) return [...new Set(alts.map(typeOf).filter((t) => t !== "null"))].join(" | ")
  return "any"
}

function paramsOf(schema) {
  const props = schema?.properties ?? {}
  const required = new Set(schema?.required ?? [])
  return Object.entries(props).map(([name, p]) => {
    const out = { name, type: typeOf(p), required: required.has(name) }
    if (p.description) out.description = p.description
    if (p.default !== undefined) out.default = JSON.stringify(p.default)
    if (p.minimum !== undefined) out.minimum = p.minimum
    if (p.maximum !== undefined) out.maximum = p.maximum
    const en = p.enum ?? (p.type === "array" ? p.items?.enum : undefined)
    if (en) out.enum = en
    return out
  })
}

/** The snapshot the reference pages are rendered from. */
export async function registrySnapshot(createServer, sdk) {
  const inv = await inventory(createServer, sdk)
  const groupOf = new Map()
  for (const g of inv.groups) for (const n of g.tools) groupOf.set(n, g.key)
  const hidden = await openAiHidden(createServer, sdk)
  const listed = await listFull(createServer, sdk, { includeProcessesTools: true })
  const order = (n) => REFERENCE_GROUPS.indexOf(groupOf.get(n))
  return listed
    .filter((t) => REFERENCE_GROUPS.includes(groupOf.get(t.name)))
    .map((t, i) => ({ t, i }))
    .sort((a, b) => order(a.t.name) - order(b.t.name) || a.i - b.i)
    .map(({ t }) => ({
      name: t.name,
      group: groupOf.get(t.name),
      title: t.annotations?.title ?? t.title ?? t.name,
      description: t.description ?? "",
      readOnly: t.annotations?.readOnlyHint === true,
      destructive: t.annotations?.destructiveHint === true,
      openWorld: t.annotations?.openWorldHint === true,
      notForOpenAi: hidden.has(t.name),
      params: paramsOf(t.inputSchema),
    }))
}

export function renderRegistryModule(snapshot) {
  return [
    "// GENERATED by scripts/gen-docs.mjs from a real tools/list. Do not edit by hand:",
    "// change the tool in src/tools/ and run `npm run docs:gen`.",
    "// tests/content/generated-docs.test.ts fails when this file is stale.",
    "",
    'import type { RegistryTool } from "../tool-reference-types"',
    "",
    `export const TOOL_REGISTRY: RegistryTool[] = ${JSON.stringify(snapshot, null, 2)}`,
    "",
  ].join("\n")
}

const mirrorSlug = (s) => (s.startsWith("mcp-") ? s : `mcp-${s}`)

/** docs/sections.json, rendered from the live sections (same shape as before). */
export function renderMirror(sections) {
  const out = sections.map((s) => ({
    slug: mirrorSlug(s.slug),
    parentSlug: mirrorSlug(s.parentSlug),
    title: s.title,
    seoTitle: s.seoTitle,
    description: s.description,
    content: s.content,
    related: s.related.map((r) => ({ label: r.label, slug: mirrorSlug(r.slug) })),
    faq: s.faq,
    mentions: s.mentions,
  }))
  return JSON.stringify(out, null, 2) + "\n"
}

async function main(argv) {
  if (argv.includes("--registry")) {
    const { createServer } = await import(join(ROOT, "dist", "index.js"))
    const { Client } = await import("@modelcontextprotocol/sdk/client/index.js")
    const { InMemoryTransport } = await import("@modelcontextprotocol/sdk/inMemory.js")
    const snap = await registrySnapshot(createServer, { Client, InMemoryTransport })
    writeFileSync(join(ROOT, REGISTRY_FILE), renderRegistryModule(snap))
    console.log(`Wrote ${REGISTRY_FILE} (${snap.length} tools).`)
  }
  if (argv.includes("--mirror")) {
    const { getAllMcpSections } = await import(join(ROOT, "dist", "content.js"))
    const text = renderMirror(getAllMcpSections())
    const before = readFileSync(join(ROOT, MIRROR_FILE), "utf8")
    writeFileSync(join(ROOT, MIRROR_FILE), text)
    console.log(`Wrote ${MIRROR_FILE}${before === text ? " (unchanged)" : ""}.`)
  }
  return 0
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv.slice(2)).then((c) => process.exit(c))
}

export { GROUPS }
